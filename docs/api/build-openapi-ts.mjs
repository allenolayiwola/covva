// Embeds docs/api/openapi.yaml into apps/web/src/server/openapi-spec.ts so GET /api/v1/openapi
// works on Vercel without file tracing. Run after editing the YAML:
//   node docs/api/build-openapi-ts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const yaml = readFileSync(join(here, "openapi.yaml"), "utf8");
const out = join(here, "../../apps/web/src/server/openapi-spec.ts");
writeFileSync(
  out,
  `// GENERATED by docs/api/build-openapi-ts.mjs from docs/api/openapi.yaml — do not edit by hand.\nexport const OPENAPI_YAML = ${JSON.stringify(yaml)};\n`,
);
console.log(`wrote ${out} (${yaml.length} bytes)`);
